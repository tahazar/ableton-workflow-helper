/**
 * File-backed library store: `<root>/clips/<category>/<slug>.md`.
 * The root is the repo's `library/` directory (or anywhere, for tests).
 */
import { mkdir, readFile, readdir, stat, writeFile } from "node:fs/promises";
import { existsSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import {
  parseClipEntry,
  serializeClipEntry,
  type ClipEntry,
} from "./entry.js";

export interface StoredClipEntry extends ClipEntry {
  /** Path of the markdown file, relative to the library root. */
  relPath: string;
}

export interface ClipFilter {
  category?: string;
  tag?: string;
}

/**
 * Locate the library root: $AWH_LIBRARY, else walk up from startDir looking
 * for an existing `library/` directory, else the first ancestor with `.git`
 * (where `library/` will be created), else `<startDir>/library`.
 */
export function findLibraryRoot(startDir: string = process.cwd()): string {
  const env = process.env.AWH_LIBRARY;
  if (env) return resolve(env);
  let dir = resolve(startDir);
  let gitRoot: string | undefined;
  for (;;) {
    if (existsSync(join(dir, "library"))) return join(dir, "library");
    if (gitRoot === undefined && existsSync(join(dir, ".git"))) gitRoot = dir;
    const parent = dirname(dir);
    if (parent === dir) break;
    dir = parent;
  }
  return join(gitRoot ?? resolve(startDir), "library");
}

export class LibraryStore {
  constructor(readonly root: string) {}

  clipFilePath(category: string, slug: string): string {
    return join(this.root, "clips", category, `${slug}.md`);
  }

  async listClips(filter: ClipFilter = {}): Promise<StoredClipEntry[]> {
    const clipsDir = join(this.root, "clips");
    if (!existsSync(clipsDir)) return [];
    const files = (await readdir(clipsDir, { recursive: true }))
      .map(String)
      .filter((f) => f.endsWith(".md") && !f.endsWith("INDEX.md"));
    const entries: StoredClipEntry[] = [];
    for (const rel of files.toSorted()) {
      const abs = join(clipsDir, rel);
      if (!(await stat(abs)).isFile()) continue;
      try {
        const entry = parseClipEntry(await readFile(abs, "utf8"));
        entries.push({ ...entry, relPath: join("clips", rel) });
      } catch (err) {
        throw new Error(`Bad library entry ${abs}: ${(err as Error).message}`);
      }
    }
    return entries.filter(
      (e) =>
        (filter.category === undefined || e.category === filter.category) &&
        (filter.tag === undefined || e.tags.includes(filter.tag)),
    );
  }

  async loadClip(slug: string): Promise<StoredClipEntry> {
    const matches = (await this.listClips()).filter((e) => e.slug === slug);
    if (matches.length === 0) throw new Error(`No library clip with slug "${slug}"`);
    if (matches.length > 1) {
      throw new Error(
        `Slug "${slug}" is ambiguous: ${matches.map((m) => m.relPath).join(", ")}`,
      );
    }
    return matches[0]!;
  }

  async saveClip(entry: ClipEntry, opts: { overwrite?: boolean } = {}): Promise<string> {
    const file = this.clipFilePath(entry.category, entry.slug);
    if (!opts.overwrite && existsSync(file)) {
      throw new Error(
        `${file} already exists — pass overwrite to replace it, or pick a new slug`,
      );
    }
    // A slug must stay unique across categories (it's the lookup key).
    const clash = (await this.listClips()).find(
      (e) => e.slug === entry.slug && e.category !== entry.category,
    );
    if (clash) {
      throw new Error(`Slug "${entry.slug}" already used by ${clash.relPath}`);
    }
    await mkdir(dirname(file), { recursive: true });
    await writeFile(file, serializeClipEntry(entry), "utf8");
    return file;
  }

  /** Regenerate `clips/INDEX.md`, the grep/browse entry point. */
  async buildIndex(): Promise<string> {
    const entries = await this.listClips();
    const byCategory = new Map<string, StoredClipEntry[]>();
    for (const e of entries) {
      const list = byCategory.get(e.category) ?? [];
      list.push(e);
      byCategory.set(e.category, list);
    }
    const lines = [
      "# Clip library index",
      "",
      `${entries.length} clips · generated by \`awh lib index\` — do not edit by hand.`,
    ];
    for (const category of [...byCategory.keys()].toSorted()) {
      lines.push("", `## ${category}`, "", "| slug | tags | bpm | scale | beats | tier |", "|---|---|---|---|---|---|");
      for (const e of byCategory.get(category)!) {
        lines.push(
          `| [${e.slug}](${e.category}/${e.slug}.md) | ${e.tags.join(", ")} | ${e.bpm ?? ""} | ${e.scale ?? ""} | ${e.lengthBeats} | ${e.tier} |`,
        );
      }
    }
    const content = `${lines.join("\n")}\n`;
    const indexPath = join(this.root, "clips", "INDEX.md");
    await mkdir(dirname(indexPath), { recursive: true });
    await writeFile(indexPath, content, "utf8");
    return content;
  }
}
